def tile_for_char(ch: str) -> int:
    if ch == " ":
        return BLANK_TILE
    return FONT_FIRST_TILE + GLYPHS.index(ch)


def glyph_tile(ch: str) -> bytes:
    if ch == " ":
        return bytes(16)
    rows = FONT5X7[ch]
    plane0 = bytearray(8)
    for y, row in enumerate(rows):
        # 5 pixels centered as bits 6..2; leave one pixel left, two right.
        plane0[y] = (row & 0x1F) << 2
    return bytes(plane0 + bytearray(8))


def install_font(chr_data: bytearray) -> None:
    for i, ch in enumerate(GLYPHS):
        tile = FONT_FIRST_TILE + i
        base = tile * 16
        chr_data[base:base + 16] = glyph_tile(ch)

    # Static graph-axis primitives. These live outside the dynamic graph range.
    axis = bytearray(16)
    axis[8] = 0xFF  # plane 1 -> palette color 2
    base = AXIS_TILE * 16
    chr_data[base:base + 16] = axis

    tick = bytearray(axis)
    tick[9] = 0x18
    tick[10] = 0x18
    tick[11] = 0x18
    base = TICK_TILE * 16
    chr_data[base:base + 16] = tick
